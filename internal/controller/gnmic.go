// gnmicPortRe limits transceiver subscriptions to front-panel ports; a port
// name is spliced into a gNMI path key, so nothing else may get through.
var gnmicPortRe = regexp.MustCompile(`^Ethernet[0-9]+(/[0-9]+)*$`)

// WriteGnmicConfig renders a gnmic configuration that subscribes to interface
// counters on every switch with gNMI settings, and to transceiver state on
// the given ports of each switch (keyed by switch name), writing it all to
// VictoriaMetrics as srnet_gnmi_* metrics. gnmic runs as its own systemd
// unit (installed by deploy/install-controller.sh), reads this file, and a
// path unit restarts it when the file changes; the file is only rewritten
// when its content would differ. With no gNMI switches configured the file
// is removed so the unit stays idle.
//
// The switch's LLDP table is not subscribed to: the same SONiC refuses the
// wildcard interface list in a Subscribe ("wildcard path not supported"),
// so the controller polls it with a gNMI Get instead (see switchLLDP).
//
// Transceiver paths are keyed per port because Enterprise SONiC rejects a
// wildcard component list ("Invalid component name"): a subscription to
// components/component/state/temperature without a key dies every few
// seconds with "queue: disposed". The per-channel path answers empty on the
// same switch; the module figures (input and output power, bias, voltage,
// form factor) live under transceiver/state, temperature under state.
func WriteGnmicConfig(cfg Config, path string, ports map[string][]string) (int, error) {
	var b strings.Builder
	n := 0
	b.WriteString("# Generated by srnet-controller from /etc/srnet/controller.json; do not edit.\n")
	b.WriteString("targets:\n")
	var xcvr strings.Builder
	for _, sw := range cfg.Switches {
		if sw.GNMIUser == "" || sw.Address == "" {
			continue
		}
		n++
		host := sw.Address
		if h, _, ok := strings.Cut(host, ":"); ok {
			host = h
		}
		port := sw.GNMIPort
		if port == 0 {
			port = 8080 // Enterprise SONiC default gNMI port
		}
		fmt.Fprintf(&b, "  %s:\n    address: %s:%d\n    username: %s\n    password: %s\n", yamlStr(sw.Name), host, port, yamlStr(sw.GNMIUser), yamlStr(sw.GNMIPassword))
		if sw.GNMITLS {
			b.WriteString("    skip-verify: true\n")
		} else {
			b.WriteString("    insecure: true\n")
		}
		names := gnmicPortList(ports[sw.Name])
		if len(names) == 0 {
			b.WriteString("    subscriptions: [counters]\n")
			continue
		}
		// One transceiver and one QoS subscription per switch, since the
		// port set is the switch's own. QoS (queue drops, ECN marks, PFC
		// pause frames) is keyed per port for the same reason as the
		// transceivers; its counters give a run its per-leg congestion
		// figures (Phase 5).
		sub := "transceivers-" + strings.ToLower(sw.Name)
		qsub := "qos-" + strings.ToLower(sw.Name)
		hsub := "health-" + strings.ToLower(sw.Name)
		fmt.Fprintf(&b, "    subscriptions: [counters, %s, %s, %s]\n", yamlStr(sub), yamlStr(qsub), yamlStr(hsub))
		fmt.Fprintf(&xcvr, "  %s:\n    paths:\n", yamlStr(sub))
		for _, p := range names {
			fmt.Fprintf(&xcvr, "      - /openconfig-platform:components/component[name=%s]/transceiver/state\n", p)
			fmt.Fprintf(&xcvr, "      - /openconfig-platform:components/component[name=%s]/state/temperature\n", p)
		}
		xcvr.WriteString("    mode: stream\n    stream-mode: sample\n    sample-interval: 60s\n    encoding: json_ietf\n")
		fmt.Fprintf(&xcvr, "  %s:\n    paths:\n", yamlStr(qsub))
		// Per port, in the one subscription (several streams at once made
		// this SONiC drop one with "queue disposed"): queue counters and
		// watermarks, ingress priority-group watermarks, PFC counters and
		// watchdog, the Ethernet error and frame-size counters, and the
		// Ethernet state (FEC mode, advertised speed).
		for _, p := range names {
			fmt.Fprintf(&xcvr, "      - /openconfig-qos:qos/interfaces/interface[interface-id=%s]/output/queues\n", p)
			fmt.Fprintf(&xcvr, "      - /openconfig-qos:qos/interfaces/interface[interface-id=%s]/input/priority-groups\n", p)
			fmt.Fprintf(&xcvr, "      - /openconfig-qos:qos/interfaces/interface[interface-id=%s]/pfc\n", p)
			fmt.Fprintf(&xcvr, "      - /openconfig-interfaces:interfaces/interface[name=%s]/openconfig-if-ethernet:ethernet/state/counters\n", p)
			fmt.Fprintf(&xcvr, "      - /openconfig-interfaces:interfaces/interface[name=%s]/openconfig-if-ethernet:ethernet/state\n", p)
		}
		xcvr.WriteString("    mode: stream\n    stream-mode: sample\n    sample-interval: 30s\n    encoding: json_ietf\n")
		// Switch CPU and memory; PSUs, fans and temperature sensors are
		// keyed by names the switch invents, so the controller polls those.
		fmt.Fprintf(&xcvr, "  %s:\n    paths:\n      - /openconfig-system:system/cpus\n      - /openconfig-system:system/memory\n", yamlStr(hsub))
		xcvr.WriteString("    mode: stream\n    stream-mode: sample\n    sample-interval: 30s\n    encoding: json_ietf\n")
	}
	if n == 0 {
		os.Remove(path)
		return 0, nil
	}
	// log: gnmic discards its log output unless asked, which hides subscribe
	// errors from the journal. encoding: Enterprise SONiC only offers
	// JSON_IETF and PROTO; gnmic's default "json" is rejected by the switch.
	// sample-interval: Enterprise SONiC 4.5 rejects anything under 30 s for
	// interface counters and under 60 s for transceivers ("Invalid Sample
	// Interval ... minimum interval is 30s" in the switch syslog).
	b.WriteString(`log: true
encoding: json_ietf
subscriptions:
  counters:
    paths:
      - /openconfig-interfaces:interfaces/interface/state/counters
      - /openconfig-interfaces:interfaces/interface/state/oper-status
      - /openconfig-interfaces:interfaces/interface/ethernet/state/port-speed
    mode: stream
    stream-mode: sample
    sample-interval: 30s
    encoding: json_ietf
`)
	b.WriteString(xcvr.String())
	b.WriteString(`outputs:
  victoriametrics:
    type: prometheus_write
    url: ` + strings.TrimRight(cfg.VictoriaMetricsURL, "/") + `/api/v1/write
    metric-prefix: srnet_gnmi
    strings-as-labels: true
    interval: 5s
`)
	out := []byte(b.String())
	if cur, err := os.ReadFile(path); err == nil && bytes.Equal(cur, out) {
		return n, nil // unchanged; a rewrite would restart gnmic for nothing
	}
	return n, os.WriteFile(path, out, 0o600)
}

// gnmicPortList keeps the valid, distinct port names in a stable order.
func gnmicPortList(ports []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, p := range ports {
		if gnmicPortRe.MatchString(p) && !seen[p] {
			seen[p] = true
			out = append(out, p)
		}
	}
	sort.Slice(out, func(i, j int) bool { return portLess(out[i], out[j]) })
	return out
}

func yamlStr(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

package controller

import (
	"fmt"
	"os"
	"strings"
)

// WriteGnmicConfig renders a gnmic configuration that subscribes to interface
// counters and transceiver state on every switch with gNMI settings and writes
// them to VictoriaMetrics as srnet_gnmi_* metrics. gnmic runs as its own
// systemd unit (installed by deploy/install-controller.sh) and reads this file.
// With no gNMI switches configured the file is removed so the unit stays idle.
func WriteGnmicConfig(cfg Config, path string) (int, error) {
	var b strings.Builder
	n := 0
	b.WriteString("# Generated by srnet-controller from /etc/srnet/controller.json; do not edit.\n")
	b.WriteString("targets:\n")
	for _, sw := range cfg.Switches {
		if sw.GNMIUser == "" || sw.Address == "" {
			continue
		}
		n++
		host := sw.Address
		if h, _, ok := strings.Cut(host, ":"); ok {
			host = h
		}
		port := sw.GNMIPort
		if port == 0 {
			port = 8080 // Enterprise SONiC default gNMI port
		}
		fmt.Fprintf(&b, "  %s:\n    address: %s:%d\n    username: %s\n    password: %s\n", yamlStr(sw.Name), host, port, yamlStr(sw.GNMIUser), yamlStr(sw.GNMIPassword))
		if sw.GNMITLS {
			b.WriteString("    skip-verify: true\n")
		} else {
			b.WriteString("    insecure: true\n")
		}
	}
	if n == 0 {
		os.Remove(path)
		return 0, nil
	}
	b.WriteString(`subscriptions:
  counters:
    paths:
      - /openconfig-interfaces:interfaces/interface/state/counters
      - /openconfig-interfaces:interfaces/interface/state/oper-status
      - /openconfig-interfaces:interfaces/interface/ethernet/state/negotiated-port-speed
    mode: stream
    stream-mode: sample
    sample-interval: 5s
  transceivers:
    paths:
      - /openconfig-platform:components/component/transceiver/physical-channels/channel/state
      - /openconfig-platform:components/component/state/temperature
    mode: stream
    stream-mode: sample
    sample-interval: 30s
outputs:
  victoriametrics:
    type: prometheus_write
    url: ` + strings.TrimRight(cfg.VictoriaMetricsURL, "/") + `/api/v1/write
    metric-prefix: srnet_gnmi
    strings-as-labels: true
    interval: 5s
`)
	return n, os.WriteFile(path, []byte(b.String()), 0o600)
}

func yamlStr(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}
